const dictionaries: Record<Language, Dictionary> = { "zh-CN": zh, en: {} };
export const resolveLanguage = (stored: string | null): Language =>
  stored === "en" ? "en" : "zh-CN";
export const translate = (language: Language, key: string) =>
  dictionaries[language][key] || key;
type I18nValue = {
  language: Language;
  setLanguage: (value: Language) => void;
  t: (key: string) => string;
};
export const I18nContext = createContext<I18nValue>({
  language: "zh-CN",
  setLanguage: () => {},
  t: (key) => key,
});

export const useI18n = () => useContext(I18nContext);
